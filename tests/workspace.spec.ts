test('真实请求路径：握手、hash 操作、认证失败和当前连接重建', async ({ page }) => {
  const calls: { method: string; params?: Record<string, unknown> }[] = []
  let requireLogin = false
  await page.route('**/transmission/rpc', async route => {
    if (requireLogin && route.request().headers().authorization !== 'Basic ' + Buffer.from('tester:not-persisted-secret').toString('base64')) { await route.fulfill({ status: 401 }); return }
    const request = route.request()
    if (!request.headers()['x-transmission-session-id']) { await route.fulfill({ status: 409, headers: { 'X-Transmission-Session-Id': 'session-a' } }); return }
    const body = request.postDataJSON()
    calls.push(body)
    if (body.method === 'session-get') await route.fulfill({ json: { result: 'success', arguments: { version: '4.1.3', 'rpc-version-semver': '6.0.0' } } })
    else await route.fulfill({ json: { jsonrpc: '2.0', id: body.id, result: body.method === 'torrent_get' ? { torrents: createDemoTorrents(3), removed: [] } : body.method === 'session_get' ? { version: '4.1.3', rpc_version_semver: '6.0.0' } : {} } })
  })
  await page.goto('/')
  await expect(page.locator('.torrent-row')).toHaveCount(3)
  await page.locator('.torrent-row').first().click()
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await expect.poll(() => calls.some(call => call.method === 'torrent_stop')).toBe(true)
  expect(calls.find(call => call.method === 'torrent_stop')?.params?.ids).toEqual(['0000000000000000000000000000000000000001'])
  requireLogin = true
  await expect(page.getByRole('dialog', { name: '登录 Transmission' })).toBeVisible({ timeout: 10000 })
  await page.screenshot({ path: '.impeccable/review/connection-error.png' })
  await expect(page.getByLabel('RPC 地址')).toHaveCount(0)
  await page.getByLabel('用户名').fill('tester')
  await page.getByLabel('密码', { exact: true }).fill('not-persisted-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('.torrent-row')).toHaveCount(3)
  await expect(page.getByText('认证失败，请检查用户名和密码')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('not-persisted-secret')
})

